func TestBidiConformance(t *testing.T) {
	for i, line := range strings.Split(bidiConformanceCases, "\n") {
		if line == "" {
			continue
		}
		parts := strings.SplitN(line, "|", 4)
		if len(parts) != 4 {
			t.Fatalf("case %d: malformed %q", i, line)
		}
		var classes []bidiClass
		for _, tok := range splitClasses(parts[0]) {
			c, ok := bidiClassNames[tok]
			if !ok {
				t.Fatalf("case %d: unknown class %q", i, tok)
			}
			classes = append(classes, c)
		}
		wantLevels := parseNums(parts[1])
		wantOrder := parseNums(parts[2])
		// The bitset field may end with a trailing comma; drop it.
		bitsStr := strings.TrimRight(strings.TrimSpace(parts[3]), ",")
		bits := 0
		for _, d := range bitsStr {
			bits = bits*16 + int(d-48)
		}
		for _, base := range []struct {
			rtl bool
			bit int
		}{{false, 2}, {true, 4}} {
			if bits&base.bit == 0 {
				continue
			}
			gotLevels := resolveBidiLevels(append([]bidiClass{}, classes...), base.rtl)
			// The Unicode reference removes BN before reordering.
			drop := make([]bool, len(classes))
			for j, c := range classes {
				drop[j] = c == bidiBN
			}
			baseLevel := 0
			if base.rtl {
				baseLevel = 1
			}
			for j, want := range wantLevels {
				if want < 0 {
					continue // unassigned (BN): excluded from output
				}
				if gotLevels[j] != want {
					t.Fatalf("case %d (%s, baseRTL=%v): level[%d]=%d want %d\nlevels: %v", i, parts[0], base.rtl, j, gotLevels[j], want, gotLevels)
				}
			}
			order := reorderBidiLine(gotLevels, drop, baseLevel)
			gotOrder := make([]int, 0, len(order))
			for _, ix := range order {
				if classes[ix] == bidiBN {
					continue // BN is omitted from the reordered output
				}
				gotOrder = append(gotOrder, ix)
			}
			if len(gotOrder) != len(wantOrder) {
				t.Fatalf("case %d (%s, baseRTL=%v): order %v want %v", i, parts[0], base.rtl, gotOrder, wantOrder)
			}
			for j := range wantOrder {
				if gotOrder[j] != wantOrder[j] {
					t.Fatalf("case %d (%s, baseRTL=%v): order[%d]=%d want %d\norder: %v want %v", i, parts[0], base.rtl, j, gotOrder[j], wantOrder[j], gotOrder, wantOrder)
				}
			}
		}
	}
}

func splitClasses(s string) []string {
	var out []string
	i := 0
	for i < len(s) {
		switch {
		case s[i] == ' ' || s[i] == '\t':
			i++
		case i+3 <= len(s) && s[i:i+3] == "NSM":
			out = append(out, "NSM")
			i += 3
		case i+2 <= len(s) && s[i:i+2] == "AL":
			out = append(out, "AL")
			i += 2
		case i+2 <= len(s) && s[i:i+2] == "AN":
			out = append(out, "AN")
			i += 2
		case i+2 <= len(s) && s[i:i+2] == "EN":
			out = append(out, "EN")
			i += 2
		case i+2 <= len(s) && s[i:i+2] == "ES":
			out = append(out, "ES")
			i += 2
		case i+2 <= len(s) && s[i:i+2] == "ET":
			out = append(out, "ET")
			i += 2
		case i+2 <= len(s) && s[i:i+2] == "CS":
			out = append(out, "CS")
			i += 2
		case i+2 <= len(s) && s[i:i+2] == "WS":
			out = append(out, "WS")
			i += 2
		case i+2 <= len(s) && s[i:i+2] == "BN":
			out = append(out, "BN")
			i += 2
		case i+2 <= len(s) && s[i:i+2] == "ON":
			out = append(out, "ON")
			i += 2
		case s[i] == 'L' || s[i] == 'R' || s[i] == 'S' || s[i] == 'B':
			out = append(out, string(s[i]))
			i++
		default:
			out = append(out, string(s[i]))
			i++
		}
	}
	return out
}

// parseNums parses comma-separated numbers; "-" or "x" mean unassigned
// (represented as -1, which the comparison loop skips).
func parseNums(s string) []int {
	if s == "" || s == "-" {
		return nil
	}
	var out []int
	n := -1
	for _, d := range s {
		if d == ',' {
			out = append(out, n)
			n = -1
			continue
		}
		if d == 'x' || d == '-' {
			n = -1
			continue
		}
		if n < 0 {
			n = 0
		}
		n = n*10 + int(d-48)
	}
	return append(out, n)
}

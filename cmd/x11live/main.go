// Command x11live drives a live go-gpui window under Xvfb: finds the
// window, sends synthetic clicks/keys, and captures screenshots so scripts
// can verify that interactive windows really respond to input.
//
//	DISPLAY=:99 go run ./cmd/x11live -do find
//	DISPLAY=:99 go run ./cmd/x11live -do click - 300,15
//	DISPLAY=:99 go run ./cmd/x11live -do key - 116
//	DISPLAY=:99 go run ./cmd/x11live -do shot - /tmp/shot.png
package main

import (
	"flag"
	"fmt"
	"os"
	"strconv"
	"strings"
	"time"

	"github.com/FlameInTheDark/go-gpui/geometry"
	"github.com/FlameInTheDark/go-gpui/platform/x11"
)

func main() {
	do := flag.String("do", "", "find | click X,Y | key CODE | shot OUT.PNG | close")
	mask := flag.Uint("mask", 0, "SendEvent event mask (0 = creator delivery)")
	flag.Parse()
	// The last positional argument carries the value (paths, X, Y, keycodes);
	// a bare "-" separator is ignored.
	var val string
	args := flag.Args()
	for _, a := range args {
		if a != "-" {
			val = a
		}
	}

	c, err := x11.Connect()
	x11.SendMask = uint32(*mask)
	if err != nil {
		fmt.Println("connect error:", err)
		os.Exit(1)
	}
	defer c.Close()

	kids, err := c.QueryTreeChildren(c.Screen().RootWindow)
	if err != nil {
		fmt.Println("querytree error:", err)
		os.Exit(1)
	}
	fmt.Println("children:", kids)
	var wid uint32
	for _, k := range kids {
		if k != 0 {
			wid = k
		}
	}
	if wid == 0 {
		fmt.Println("no window found")
		os.Exit(1)
	}
	fmt.Println("window:", wid)

	switch *do {
	case "find":
		// Window discovered above.
	case "click":
		parts := strings.SplitN(val, ",", 2)
		if len(parts) != 2 {
			fmt.Println("click wants X,Y")
			os.Exit(1)
		}
		x, _ := strconv.Atoi(parts[0])
		y, _ := strconv.Atoi(parts[1])
		if err := c.SendTestClickXTest(wid, int16(x), int16(y)); err != nil {
			fmt.Println("click error:", err)
			os.Exit(1)
		}
		// Round-trip: surfaces any X error generated by the fake input.
		if _, err := c.QueryTreeChildren(c.Screen().RootWindow); err != nil {
			fmt.Println("post-click X error:", err)
		}
		fmt.Println("clicked", x, y)
	case "close":
		proto, _ := c.InternAtom("WM_PROTOCOLS", true)
		del, _ := c.InternAtom("WM_DELETE_WINDOW", true)
		if proto == 0 || del == 0 {
			fmt.Println("atoms missing", proto, del)
			os.Exit(1)
		}
		if err := c.SendTestClientMessage(wid, proto, [5]uint32{del, 0, 0, 0, 0}); err != nil {
			fmt.Println("close error:", err)
			os.Exit(1)
		}
		fmt.Println("close sent")
	case "key":
		code, _ := strconv.Atoi(val)
		if err := c.SendTestKey(wid, byte(code), true, 0); err != nil {
			fmt.Println("key error:", err)
			os.Exit(1)
		}
		if err := c.SendTestKey(wid, byte(code), false, 0); err != nil {
			fmt.Println("key-release error:", err)
			os.Exit(1)
		}
		fmt.Println("key", code)
	case "shot":
		time.Sleep(300 * time.Millisecond)
		png, err := x11.CaptureScreenPNG(geometry.Bounds[int32]{
			Origin: geometry.Point[int32]{X: 100, Y: 100},
			Size:   geometry.Size[int32]{Width: 960, Height: 600},
		})
		if err != nil {
			fmt.Println("capture error:", err)
			os.Exit(1)
		}
		if err := os.WriteFile(val, png, 0o644); err != nil {
			fmt.Println("write error:", err)
			os.Exit(1)
		}
		fmt.Println("shot saved", len(png))
	default:
		fmt.Println("unknown -do")
		os.Exit(1)
	}
}

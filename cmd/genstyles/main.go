// Command genstyles generates:
//
//   - style/styled_gen.go: the numeric Tailwind-style scale methods on
//     StyleRefinement (W_8, P_2, Gap_4, Rounded_Md, Shadow_Lg, Text_Xs, ...)
//   - elements/styled_forward_gen.go: forwarders that give element types
//     (Div, Svg, Img, ...) the full Styled builder surface, the Go
//     equivalent of Rust's `impl Styled for T`.
//
// The tables mirror the upstream editor's crates/gpui_macros/src/styles.rs.
//
// Every generated style method carries a godoc comment produced from the
// templates in this file (see scaleComment, familyDocs and shadowMethods);
// edit the templates, never the generated files. style/styled_gen.go is run
// through go/format by the generator, so a regeneration is gofmt-clean.
//
// Run it from the repository root:
//
//	go run ./cmd/genstyles
//
// The numeric scale follows Tailwind: one unit is 0.25rem (W_4 = 1rem),
// "px" is one pixel, "full" is 100%, and N_M suffixes (1_2, 2_3, ...) are
// fractions of the parent size. Negative variants (M_Neg_4) exist for the
// margin and inset families only.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

type boxSuffix struct {
	suffix string
	value  string
}

type family struct {
	prefix    string
	paramName string // refinement method to call
	kind      string // "length", "definite"
	autoOK    bool
	neg       bool
	fullOK    bool
}

// handMethod describes one hand-written builder method signature.
type handMethod struct {
	name string
	args string // e.g. "l geometry.Length"
	call string // e.g. "l" - forwarded call args
}

func main() {
	generateRefinement()
	generateForwarders()
}


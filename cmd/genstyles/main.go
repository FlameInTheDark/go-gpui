func generateForwarders() {
	elements := []struct {
		Type string
		Acc  string // style accessor expression
	}{
		{"Div", "d.StyleRef()"},
		{"Svg", "s.StyleRef()"},
		{"Img", "i.StyleRef()"},
		{"Canvas", "c.StyleRef()"},
		{"List", "l.StyleRef()"},
		{"UniformList", "u.StyleRef()"},
	}

	var b bytes.Buffer
	b.WriteString(`// Code generated by cmd/genstyles. DO NOT EDIT.
// Forwarders giving element types the full Styled builder surface — the Go
// equivalent of Rust's ` + "`impl Styled for T`" + `.

package elements

import (
	gc "github.com/FlameInTheDark/go-gpui/color"
	"github.com/FlameInTheDark/go-gpui/font"
	"github.com/FlameInTheDark/go-gpui/geometry"
	st "github.com/FlameInTheDark/go-gpui/style"
)

`)

	for _, el := range elements {
		for _, m := range allMethods() {
			refName := m.refName
			if refName == "" {
				refName = m.name
			}
			refArgs := m.refArgs
			args := m.args
			recv := strings.ToLower(el.Type[:1])
			if refArgs == "" && args != "" {
				refArgs = firstIdentifiers(args)
			}
			// Rename call args that collide with the receiver.
			if refArgs == recv {
				refArgs = "v"
				args = renameFirstArg(args, recv, "v")
			}
			if args == "" {
				fmt.Fprintf(&b, "func (%s *%s) %s() *%s { %s.%s(); return %s }\n",
					recv, el.Type, m.name, el.Type, el.Acc, refName, recv)
			} else {
				fmt.Fprintf(&b, "func (%s *%s) %s(%s) *%s { %s.%s(%s); return %s }\n",
					recv, el.Type, m.name, args, el.Type, el.Acc, refName, refArgs, recv)
			}
		}
		b.WriteString("\n")
	}

	out := b.Bytes()
	dst := filepath.Join("elements", "styled_forward_gen.go")
	if err := os.WriteFile(dst, out, 0o644); err != nil {
		panic(err)
	}
	fmt.Printf("wrote %s (%d bytes)\n", dst, len(out))
}

// renameFirstArg renames the first parameter of an arg list.
func renameFirstArg(args, from, to string) string {
	parts := strings.SplitN(args, ",", 2)
	fields := strings.Fields(parts[0])
	if len(fields) > 0 && fields[0] == from {
		fields[0] = to
	}
	parts[0] = strings.Join(fields, " ")
	return strings.Join(parts, ", ")
}

// firstIdentifiers extracts the parameter names from an arg list like
// "l geometry.Length" -> "l", "w, h geometry.Length" -> "w, h".
func firstIdentifiers(args string) string {
	var names []string
	for _, part := range strings.Split(args, ",") {
		part = strings.TrimSpace(part)
		fields := strings.Fields(part)
		if len(fields) > 0 {
			names = append(names, fields[0])
		}
	}
	return strings.Join(names, ", ")
}

func emitCall(b *bytes.Buffer, f family, suffix, kind, ctor, value string, sign int) {
	var expr string
	signPrefix := ""
	signedValue := value
	if sign < 0 {
		signPrefix = "-"
		signedValue = "(" + value + ")"
	}
	switch ctor {
	case "px":
		if kind == "definite" {
			expr = fmt.Sprintf("geometry.PixelsDefinite(geometry.Px(%s%s))", signPrefix, signedValue)
		} else {
			expr = fmt.Sprintf("geometry.LengthFromPixels(geometry.Px(%s%s))", signPrefix, signedValue)
		}
	case "rems":
		if kind == "definite" {
			expr = fmt.Sprintf("geometry.RemsDefinite(geometry.Rems(%s%s))", signPrefix, signedValue)
		} else {
			expr = fmt.Sprintf("geometry.LengthFromRems(geometry.Rems(%s%s))", signPrefix, signedValue)
		}
	default:
		if kind == "definite" {
			expr = fmt.Sprintf("geometry.RelativeDefinite(%s%s)", signPrefix, signedValue)
		} else {
			expr = fmt.Sprintf("geometry.LengthFromDefinite(geometry.RelativeDefinite(%s%s))", signPrefix, signedValue)
		}
	}
	name := methodName(f.prefix, suffix)
	fmt.Fprintf(b, "// %s\nfunc (r *StyleRefinement) %s() *StyleRefinement { return r.%s(%s) }\n\n", scaleComment(name, f, suffix, ctor, value, sign), name, f.paramName, expr)
}

// familyDoc names the CSS property a numeric scale family writes and its
// Tailwind class prefix, for the generated comments.
type familyDoc struct {
	what string // "width": completes "sets the <what> to ..."
	tw   string // Tailwind class prefix: "w", "min-w", "gap-x", ...
}

var familyDocs = map[string]familyDoc{
	"w": {"width", "w"}, "h": {"height", "h"}, "size": {"width and height", "size"},
	"min_w": {"minimum width", "min-w"}, "min_h": {"minimum height", "min-h"},
	"max_w": {"maximum width", "max-w"}, "max_h": {"maximum height", "max-h"},
	"m": {"margin on all sides", "m"}, "mt": {"top margin", "mt"}, "mb": {"bottom margin", "mb"},
	"my": {"top and bottom margin", "my"}, "mx": {"left and right margin", "mx"},
	"ml": {"left margin", "ml"}, "mr": {"right margin", "mr"},
	"p": {"padding on all sides", "p"}, "pt": {"top padding", "pt"}, "pb": {"bottom padding", "pb"},
	"py": {"top and bottom padding", "py"}, "px": {"left and right padding", "px"},
	"pl": {"left padding", "pl"}, "pr": {"right padding", "pr"},
	"gap": {"row and column gap", "gap"}, "gap_x": {"column gap", "gap-x"}, "gap_y": {"row gap", "gap-y"},
	"top": {"top inset", "top"}, "bottom": {"bottom inset", "bottom"},
	"left": {"left inset", "left"}, "right": {"right inset", "right"},
	"inset": {"inset on all four sides", "inset"},
}

// tailwindClass builds the Tailwind class for a prefix and a generator
// suffix: ("w", "0p5") -> "w-0.5", ("m", "neg_1_2") -> "-m-1/2".
func tailwindClass(prefix, suffix string) string {
	neg := strings.HasPrefix(suffix, "neg_")
	s := strings.TrimPrefix(suffix, "neg_")
	s = strings.ReplaceAll(s, "p5", ".5")
	s = strings.ReplaceAll(s, "_", "/")
	cls := prefix + "-" + s
	if neg {
		cls = "-" + cls
	}
	return cls
}

// scaleComment renders the godoc sentence of one numeric scale method.
func scaleComment(name string, f family, suffix, ctor, value string, sign int) string {
	d := familyDocs[f.prefix]
	var val string
	switch ctor {
	case "relative":
		if suffix == "full" {
			val = "100% of the parent size"
		} else {
			val = fractionPercent(suffix, sign) + " of the parent size"
		}
	case "px":
		val = signedNumber(value, sign) + "px"
	default:
		val = signedNumber(value, sign) + "rem"
	}
	return fmt.Sprintf("%s sets the %s to %s (Tailwind %s).", name, d.what, val, tailwindClass(d.tw, suffix))
}

// signedNumber formats a numeric literal compactly ("2.0" -> "2"),
// negated when sign < 0 and the value is non-zero.
func signedNumber(value string, sign int) string {
	v, err := strconv.ParseFloat(value, 64)
	if err != nil {
		panic(err)
	}
	if sign < 0 && v != 0 {
		v = -v
	}
	return strconv.FormatFloat(v, 'f', -1, 64)
}

// fractionPercent turns a suffix such as "1_3" or "neg_5_6" into "33.33%"
// (negated for neg_ suffixes).
func fractionPercent(suffix string, sign int) string {
	parts := strings.Split(strings.TrimPrefix(suffix, "neg_"), "_")
	num, _ := strconv.ParseFloat(parts[0], 64)
	den, _ := strconv.ParseFloat(parts[1], 64)
	pct := num / den * 100
	if sign < 0 {
		pct = -pct
	}
	return strconv.FormatFloat(pct, 'g', 4, 64) + "%"
}

// methodName builds the Go method name for prefix+suffix: "w"+"8" -> "W_8",
// "gap_x"+"2" -> "GapX_2", "m"+"neg_1" -> "M_Neg_1".
func methodName(prefix, suffix string) string {
	p := goCase(prefix)
	if suffix == "" {
		return p
	}
	s := strings.ToUpper(suffix[:1]) + suffix[1:]
	return p + "_" + s
}

// goCase converts snake_case to CamelCase: "gap_x" -> "GapX".
func goCase(s string) string {
	parts := strings.Split(s, "_")
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}
